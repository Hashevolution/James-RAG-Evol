def render_readme(pack_id: str) -> str:
    """Render the README.md template."""
    return (
        "# " + pack_id + "\n\n"
        "Ontology pack for JAMES (`core/ontology_packs.py` mount "
        "mechanism).\n\n"
        "Scaffolded by `python -m james.pack init " + pack_id + "`.\n"
        "See `docs/ONTOLOGY_PACK_AUTHORING.md` (in the JAMES repo) "
        "for the author guide.\n\n"
        "## Quickstart\n\n"
        "```bash\n"
        "# 1. Edit pack.py — add your subtypes / relations / roles.\n"
        "# 2. Run the smoke test:\n"
        "pytest test_pack.py\n\n"
        "# 3. In your JAMES deployment, grant the capability\n"
        "#    (or use the default rule_one_exemption_granted) and mount:\n"
        "export JAMES_CAPABILITIES=\"rule_one_exemption_granted\"\n"
        "python -c \"from pack import "
        + _module_safe_name(pack_id).upper() + "_PACK; "
        "from core.ontology_packs import register_pack; "
        "register_pack(" + _module_safe_name(pack_id).upper()
        + "_PACK); print('mounted')\"\n"
        "```\n\n"
        "## License\n\n"
        "MIT — see `LICENSE`.\n"
    )


def scaffold_files(pack_id: str) -> Dict[str, str]:
    """Render all 4 canonical files as a name → content dict.

    Pure function; no I/O. The caller (CLI) writes them.
    """
    validate_pack_id(pack_id)
    return {
        "pack.py":      render_pack_py(pack_id),
        "test_pack.py": render_test_pack_py(pack_id),
        "LICENSE":      render_license(),
        "README.md":    render_readme(pack_id),
    }


def write_scaffold(pack_id: str, output_dir: str,
                   *, overwrite: bool = False) -> List[str]:
    """Write the scaffold to ``<output_dir>/<pack_id>/``.

    Args:
        pack_id: pack identifier (validated).
        output_dir: parent directory; the pack subdir is created
            under it.
        overwrite: when False (default), refuses to overwrite an
            existing directory; raises ``FileExistsError``. When
            True, writes over existing files (use sparingly).

    Returns:
        Sorted list of relative file paths written.
    """
    validate_pack_id(pack_id)
    pack_dir = os.path.join(output_dir, pack_id)
    if os.path.exists(pack_dir) and not overwrite:
        raise FileExistsError(
            f"refusing to write to existing directory "
            f"{pack_dir!r}; pass --overwrite to force"
        )
    os.makedirs(pack_dir, exist_ok=True)
    written: List[str] = []
    for fname, content in scaffold_files(pack_id).items():
        path = os.path.join(pack_dir, fname)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        written.append(os.path.join(pack_id, fname))
    written.sort()
    return written


