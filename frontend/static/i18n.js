// Default: English
let currentLang = localStorage.getItem('james_lang') || 'en';

function t(key, vars) {
  vars = vars || {};
  var dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  var text = dict[key] || TRANSLATIONS.en[key] || key;
  for (var k in vars) {
    text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
  }
  return text;
}

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem('james_lang', lang);
  applyTranslations();
  if (typeof onLangChange === 'function') onLangChange(lang);
}

function getLang() {
  return currentLang;
}

function toggleLang() {
  setLang(currentLang === 'en' ? 'ko' : 'en');
}

// Toggle button display: KO | EN both visible, active highlighted
function updateLangToggleDisplay() {
  var btns = document.querySelectorAll('[data-lang-toggle]');
  for (var i = 0; i < btns.length; i++) {
    var koActive = currentLang === 'ko';
    btns[i].innerHTML =
      '<span style="opacity:' + (koActive ? 1 : 0.4) + ';font-weight:' + (koActive ? 700 : 400) + '">KO</span>' +
      '<span style="opacity:0.5;margin:0 4px">|</span>' +
      '<span style="opacity:' + (!koActive ? 1 : 0.4) + ';font-weight:' + (!koActive ? 700 : 400) + '">EN</span>';
  }
}

function applyTranslations() {
  var els = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < els.length; i++) {
    var el = els[i];
    var key = el.getAttribute('data-i18n');
    if (key) {
      if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = t(key);
      } else {
        el.textContent = t(key);
      }
    }
  }
  var phs = document.querySelectorAll('[data-i18n-placeholder]');
  for (var i = 0; i < phs.length; i++) {
    var key = phs[i].getAttribute('data-i18n-placeholder');
    if (key) phs[i].placeholder = t(key);
  }
  var titles = document.querySelectorAll('[data-i18n-title]');
  for (var i = 0; i < titles.length; i++) {
    var key = titles[i].getAttribute('data-i18n-title');
    if (key) titles[i].title = t(key);
  }
  updateLangToggleDisplay();
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyTranslations);
  } else {
    applyTranslations();
  }
}
